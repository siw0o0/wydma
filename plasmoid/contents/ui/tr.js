// Język z ustawień albo, przy „auto”, z systemu: polski dla polskiego, angielski dla reszty.
function pick(setting) {
    if (setting === "pl" || setting === "en") return setting;
    return Qt.locale().name.split("_")[0] === "pl" ? "pl" : "en";
}

function tr(lang, text) {
    var out = lang === "pl" ? text : (en[text] || text);
    for (var i = 2; i < arguments.length; i++)
        if (arguments[i] !== undefined) out = out.replace("%" + (i - 1), arguments[i]);
    return out;
}
